    public void mostrarDatosServicio(ServicioLuz s) {
        lblNombre.setText(s.getNombreCliente());
        lblDireccion.setText(s.getDireccion());
        lblPeriodo.setText(s.getPeriodo());
        lblConsumo.setText(s.getConsumoKw() + " kw");
        lblMonto.setText("$" + s.getMontoPagar());
        btnCPagar.setEnabled(true);
        jLabel3.setVisible(true);
        jLabel4.setVisible(true);
        jLabel5.setVisible(true);
        jLabel6.setVisible(true);
        jLabel7.setVisible(true);
    }

    public void activarModoRecibo(Recibo recibo) {
        lblFolio.setText(recibo.getFolio());
        lblMensajeExito.setText("Pago Realizado Con Exito");
        lblFechaR.setText(recibo.getFecha().toString());
        lblImporteP.setText("$" + recibo.getImporteTotal());
        panelRecibo.setVisible(true); 
        btnCPagar.setText("Imprimir Comprobante y Salir");
    }
    
