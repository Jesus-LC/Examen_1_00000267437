    class SoloLetrasMayusculasDocument extends PlainDocument {
        @Override
        public void insertString(int offset, String str, AttributeSet attr) throws BadLocationException {
            if (str == null) return;
            String filtered = str.toUpperCase().replaceAll("[^A-ZÁÉÍÓÚÑ ]", "");
            super.insertString(offset, filtered, attr);
        }
    }

    //Solo números y formato de tarjeta 4 en 4
    class FormatoTarjetaDocument extends PlainDocument {
        @Override
        public void insertString(int offset, String str, AttributeSet attr) throws BadLocationException {
            if (str == null) return;
            String soloDigitos = str.replaceAll("[^0-9]", "");
            String actualText = getText(0, getLength());
            int digitosActuales = actualText.replaceAll(" ", "").length();
            if (digitosActuales >= 16) return; 

            super.insertString(offset, soloDigitos, attr);
            formatCardText();
        }
        
        @Override
        public void remove(int offset, int length) throws BadLocationException {
            super.remove(offset, length);
            formatCardText();
        }

        private void formatCardText() {
            try {
                String text = getText(0, getLength()).replaceAll(" ", "");
                StringBuilder formatted = new StringBuilder();
                for (int i = 0; i < text.length(); i++) {
                    if (i > 0 && i % 4 == 0) {
                        formatted.append(" ");
                    }
                    formatted.append(text.charAt(i));
                }
                if (!formatted.toString().equals(getText(0, getLength()))) {
                    super.remove(0, getLength());
                    super.insertString(0, formatted.toString(), null);
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }

   
    class FormatoFechaDocument extends PlainDocument {
        @Override
        public void insertString(int offset, String str, AttributeSet attr) throws BadLocationException {
            if (str == null) return;
            String soloDigitos = str.replaceAll("[^0-9]", "");
            String currentText = getText(0, getLength());
            if (currentText.length() >= 5) return; 
            super.insertString(offset, soloDigitos, attr);
            String updatedText = getText(0, getLength()).replaceAll("/", "");
            if (updatedText.length() >= 2) {
                String formatted = updatedText.substring(0, 2) + (updatedText.length() > 2 ? "/" + updatedText.substring(2, Math.min(updatedText.length(), 4)) : "");
                super.remove(0, getLength());
                super.insertString(0, formatted, null);
            }
        }
    }

    
    class SoloNumerosDocument extends PlainDocument {
        private int limite;

        public SoloNumerosDocument(int limite) {
            this.limite = limite;
        }

        @Override
        public void insertString(int offset, String str, AttributeSet attr) throws BadLocationException {
            if (str == null) return;
            String soloDigitos = str.replaceAll("[^0-9]", "");
            if ((getLength() + soloDigitos.length()) > limite) {
                return;
            }
            super.insertString(offset, soloDigitos, attr);
        }
    }

